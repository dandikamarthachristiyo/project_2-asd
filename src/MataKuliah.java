public class MataKuliah {
    String kode;
    String nama;
    int sks;
    int semester;
    String ganjilGenap;

    public MataKuliah(String kode, String nama, int sks, int semester, String ganjilGenap) {
        this.kode = kode;
        this.nama = nama;
        this.sks = sks;
        this.semester = semester;
        this.ganjilGenap = ganjilGenap;
    }
}
